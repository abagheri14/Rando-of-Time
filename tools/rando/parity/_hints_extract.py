"""Copy the vanilla text the hints plugin rewrites, in every language, into data/rando/hints_messages.json.

usage: python tools/rando/parity/_hints_extract.py ROMFS

The plugin builds each hint message on the vanilla one (its speaker, voice and style tags, the pages it keeps) and
names places and items as the game does, per language. Generation runs without the game files, so the text it needs
is copied here once (read through romtools.Romfs with ./original, so vanilla copies of patched archives win):
  messages: {"<file>:<label>": {lang: markup}} for every message in data/rando/hints_targets.json and every
            Gossip Stone rumour (GossipStone.msbt GOSSIP_*)
  names:    {lang: {"location": {LocationMsg label: name}, "item": {PouchContent actor: name}, "player": name}}
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
sys.path.insert(0, os.path.join(HERE, "tools"))
TARGETS = os.path.join(HERE, "data", "rando", "hints_targets.json")
OUT = os.path.join(HERE, "data", "rando", "hints_messages.json")


def target_messages(t):
    """Every (file, label) the targets file names."""
    out = []
    for spec in t["targets"].values():
        out.append((spec["file"], spec["label"]))
        out += [(a["file"], a["label"]) for a in spec.get("also", [])]
    for key, spec in t["warp_songs"].items():
        if key.startswith("_"):
            continue
        out += [("EventFlowMsg/Dm_SY_Ocarina.msbt", spec["confirm"]), ("LayoutMsg/Ocarina_00.msbt", spec["caption"]),
                ("ActorMsg/PouchContent.msbt", spec["get_caption"])]
    for key, specs in t["owls"].items():
        if key.startswith("_"):
            continue
        out += [(s["file"], s["label"]) for s in specs]
    return sorted(set(out))


def main(romfs):
    import msbt
    from romtools import Romfs
    fs = Romfs(romfs, os.path.join(HERE, "original"))
    t = json.load(open(TARGETS, encoding="utf-8"))
    wanted = target_messages(t)
    first = msbt.Msbt(msbt.read_archive(fs, "USen")["EventFlowMsg/GossipStone.msbt"])
    wanted += [("EventFlowMsg/GossipStone.msbt", k) for k in first.labels if k.startswith("GOSSIP_")]
    messages, names = {}, {}
    for lang in msbt.archives(romfs):
        files = msbt.read_archive(fs, lang)
        cache = {}

        def get(name):
            if name not in cache:
                cache[name] = msbt.Msbt(files[name])
            return cache[name]
        for f, label in wanted:
            m = get(f)
            if label not in m.labels:
                raise SystemExit(f"{lang}: no message {f}:{label}")
            messages.setdefault(f"{f}:{label}", {})[lang] = m.markup(label)
        loc = get("LocationMsg/Location.msbt")
        pc = get("ActorMsg/PouchContent.msbt")
        ref = get("StaticMsg/Reference.msbt")
        names[lang] = {"location": {k: loc.text(k) for k in loc.labels},
                       "item": {k[:-5]: pc.text(k) for k in pc.labels if k.endswith("_Name")},
                       "player": ref.text("PlayerName") if "PlayerName" in ref.labels else "Link"}
    out = {"_about": __doc__.strip().splitlines()[0] + " Generated by tools/rando/parity/_hints_extract.py; "
                     "don't edit by hand.", "messages": messages, "names": names}
    json.dump(out, open(OUT, "w", encoding="utf-8"), indent=0, ensure_ascii=False, sort_keys=True)
    print(f"{len(messages)} messages and the name tables in {len(names)} languages -> {OUT}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
