"""Shared base of the game-logic index (tools/gamedb), with the paths, the cache and the per-file builder protocol.

The index reads the remake's files and caches what they say about the game's logic as JSON in cache/gamedb/. For
vanilla, ./original wins over a patched live file like everywhere else. The cache folder is generated and ignores
itself.

Builder protocol, one module per section (levels, events, logic, actors, gamedata):

    SECTION = "levels"              # cache file name: cache/gamedb/<tag>/levels.json
    VERSION = 1                     # bump when the record shape changes (the cache is rebuilt)
    def files(root): -> [rel, ...]  # the files of this section that exist under a romfs-shaped folder (the game's
                                    #   romfs, or a built patch's folder: only the files it holds are re-indexed)
    def index_file(fs, rel): -> obj # what one file says (JSON-able), read through fs (a romtools.Romfs)
    def finish(fs, by_file): -> obj # optional: cross-file summaries, stored as "summary" (recomputed after overlays)

The cache file is {"meta": {...}, "by_file": {rel: obj}, "summary": obj}. An overlay index (a seed's patch) starts
from the base index and replaces the entries of the files the patch holds, so "the game as this seed's patch makes it"
only costs the patched files.
"""
import json
import os
import re
import sys
import time

HERE = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))  # project root
TOOLS = os.path.join(HERE, "tools")
if TOOLS not in sys.path:
    sys.path.insert(0, TOOLS)

from romtools import Romfs, byml_load, murmur3_32, sarc_files  # noqa: E402,F401

DEFAULT_ROMFS = os.environ.get("REMAKE_ROMFS") or __import__("romtools").longshot_romfs()
ORIGINAL = os.path.join(HERE, "original")
CACHE = os.path.join(HERE, "cache", "gamedb")
BASE_TAG = "vanilla"
SCHEMA = 1
ZSTD_MAGIC = b"\x28\xb5\x2f\xfd"


def open_romfs(romfs=None, overlays=()):
    """The game as vanilla (./original first), optionally with built patch folders laid over it."""
    return Romfs(romfs or DEFAULT_ROMFS, ORIGINAL, [os.path.abspath(o) for o in overlays])


def read_any(fs, rel):
    """A file's bytes, zstd-decompressed when compressed (Logic/*.ainb are stored raw, most others .zs)."""
    raw = fs.raw(rel)
    return fs.zs.decompress(raw) if raw[:4] == ZSTD_MAGIC else raw


def read_byml(fs, rel):
    root, _ = byml_load(read_any(fs, rel), allow_big=True)
    return root


def pack(fs, rel):
    """{inner path: bytes} of a .pack.zs (SARC)."""
    return sarc_files(read_any(fs, rel))


def list_files(root, sub, pattern):
    """Rel paths (forward slashes) of the files directly in root/sub whose name matches the regex pattern."""
    d = os.path.join(root, sub)
    if not os.path.isdir(d):
        return []
    rx = re.compile(pattern)
    return sorted(f"{sub}/{f}" for f in os.listdir(d) if rx.search(f) and os.path.isfile(os.path.join(d, f)))


_VER = re.compile(r"^(?P<base>.+?)(?:\.(?P<ver>\d{3}))?\.(?P<ext>bfevfl\.zs|rstbl\.byml\.zs|byml\.zs)$")


def versioned(fn):
    """("Get_Foo", 110 or -1) for Get_Foo.110.bfevfl.zs / Get_Foo.bfevfl.zs. The game reads the newest version."""
    m = _VER.match(os.path.basename(fn))
    if not m:
        return os.path.basename(fn), -1
    return m.group("base"), int(m.group("ver") or -1)


def newest_only(rels):
    """Keeps only the version of a file the game reads, out of several (X.bfevfl.zs, X.110.bfevfl.zs)."""
    best = {}
    for r in rels:
        base, ver = versioned(r)
        key = (os.path.dirname(r), base)
        if key not in best or ver > best[key][0]:
            best[key] = (ver, r)
    return sorted(r for _, r in best.values())


# Cache

def cache_dir(tag=BASE_TAG):
    d = os.path.join(CACHE, tag)
    os.makedirs(d, exist_ok=True)
    ign = os.path.join(CACHE, ".gitignore")
    if not os.path.exists(ign):
        with open(ign, "w", encoding="utf-8") as f:
            f.write("# generated by tools/gamedb/build.py; rebuild with: python tools/gamedb/build.py\n*\n")
    return d


def cache_path(section, tag=BASE_TAG):
    return os.path.join(cache_dir(tag), f"{section}.json")


def save(section, doc, tag=BASE_TAG):
    p = cache_path(section, tag)
    tmp = p + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(doc, f, ensure_ascii=False, separators=(",", ":"), default=_json_default)
    os.replace(tmp, p)
    with open(p[:-5] + ".meta.json", "w", encoding="utf-8") as f:  # build.check reads just the metadata.
        json.dump(doc.get("meta", {}), f, indent=1)
    return p


def load_meta(section, tag=BASE_TAG):
    p = cache_path(section, tag)[:-5] + ".meta.json"
    if not os.path.exists(p):
        return None
    with open(p, encoding="utf-8") as f:
        return json.load(f)


def load(section, tag=BASE_TAG):
    p = cache_path(section, tag)
    if not os.path.exists(p):
        raise FileNotFoundError(f"no gamedb cache {p}: run python tools/gamedb/build.py"
                                + (f" --overlay <patch folder> --tag {tag}" if tag != BASE_TAG else ""))
    with open(p, encoding="utf-8") as f:
        return json.load(f)


def _json_default(v):
    if isinstance(v, (bytes, bytearray)):
        return v.hex()
    if isinstance(v, (set, frozenset, tuple)):
        return sorted(v) if isinstance(v, (set, frozenset)) else list(v)
    if hasattr(v, "item"):  # numpy-like scalars
        return v.item()
    return str(v)


def meta(section, version, fs, n_files, seconds, overlays=()):
    return {"schema": SCHEMA, "section": section, "version": version, "romfs": fs.root,
            "original": fs.vanilla, "overlays": list(overlays), "files": n_files,
            "built": time.strftime("%Y-%m-%d %H:%M:%S"), "seconds": round(seconds, 1)}


def jsonable(v):
    """Plain JSON data from byml values (U32/I64/U64/F64 subclasses, HashDict, Bin)."""
    if isinstance(v, dict):
        return {str(k): jsonable(x) for k, x in v.items()}
    if isinstance(v, (list, tuple)):
        return [jsonable(x) for x in v]
    if isinstance(v, bool) or v is None:
        return v
    if isinstance(v, int):
        return int(v)
    if isinstance(v, float):
        return float(v)
    if isinstance(v, (bytes, bytearray)):
        return bytes(v).hex()
    return v if isinstance(v, str) else str(v)


def rnd(v, n=2):
    return [round(float(x), n) for x in v] if isinstance(v, (list, tuple)) else round(float(v), n)
